def normalize_food_name(name: str) -> str:
    """Normalizes a food name for deduplication and indexing."""
    if not name:
        return ""
    return re.sub(r"\s+", " ", str(name).strip().lower())


def seed_nourish_catalog(db=None):
    """Idempotently seeds public Nourish food catalog and migrated recipes into PostgreSQL."""
    own_db = False
    if db is None:
        from db_pg import get_db, close_db
        db = get_db()
        own_db = True

    inserted_foods = 0
    inserted_recipes = 0
    try:
        food_sql = """
            INSERT INTO nourish_food_catalog (
                name, normalized_name, brand, category, source, is_public,
                calories_per_100g, protein_per_100g, carbs_per_100g, fat_per_100g,
                fiber_per_100g, sugar_per_100g, sodium_mg_per_100g,
                serving_label, serving_weight_g, is_liquid, prep_state, ai_verified
            ) VALUES (
                %s, %s, %s, %s, %s, %s,
                %s, %s, %s, %s,
                %s, %s, %s,
                %s, %s, %s, %s, %s
            )
            ON CONFLICT (normalized_name) WHERE is_public = TRUE DO NOTHING
        """
        for item in CURATED_AND_MIGRATED_FOODS:
            norm = normalize_food_name(item.get("normalized_name") or item["name"])
            params = (
                item["name"],
                norm,
                item.get("brand", ""),
                item.get("category", "General"),
                item.get("source", "curated"),
                bool(item.get("is_public", True)),
                float(item.get("calories_per_100g", 0)),
                float(item.get("protein_per_100g", 0)),
                float(item.get("carbs_per_100g", 0)),
                float(item.get("fat_per_100g", 0)),
                float(item.get("fiber_per_100g", 0)),
                float(item.get("sugar_per_100g", 0)),
                float(item.get("sodium_mg_per_100g", 0)),
                item.get("serving_label", "1 serving (100g)"),
                float(item.get("serving_weight_g", 100)),
                bool(item.get("is_liquid", False)),
                item.get("prep_state", "as_is"),
                bool(item.get("ai_verified", True)),
            )
            db.execute(food_sql, params)
            inserted_foods += getattr(db, "rowcount", 0) or 0

        recipe_sql = """
            INSERT INTO nourish_recipes (
                household_id, created_by_user_id, linked_recipe_id, name,
                servings, total_cooked_weight_g, total_volume_ml, density_g_per_ml,
                serving_weight_g, raw_ingredients_text, ingredients_json,
                calories_per_serving, protein_per_serving, carbs_per_serving, fat_per_serving,
                fiber_per_serving, sugar_per_serving, sodium_mg_per_serving,
                calories_per_100g, protein_per_100g, carbs_per_100g, fat_per_100g, fiber_per_100g,
                ai_notes, is_public
            )
            SELECT
                NULL, NULL, NULL, %s,
                %s, %s, %s, %s,
                %s, %s, %s::jsonb,
                %s, %s, %s, %s,
                %s, %s, %s,
                %s, %s, %s, %s, %s,
                %s, TRUE
            WHERE NOT EXISTS (
                SELECT 1 FROM nourish_recipes
                WHERE LOWER(name) = LOWER(%s) AND is_public = TRUE
            )
        """
        for rec in MIGRATED_RECIPES:
            r_params = (
                rec["name"],
                float(rec.get("servings", 4)),
                float(rec.get("total_cooked_weight_g", 400)),
                float(rec["total_volume_ml"]) if rec.get("total_volume_ml") is not None else None,
                float(rec.get("density_g_per_ml", 1.050)),
                float(rec.get("serving_weight_g", 100)),
                rec.get("raw_ingredients_text", ""),
                json.dumps(rec.get("ingredients_json", [])),
                float(rec.get("calories_per_serving", 0)),
                float(rec.get("protein_per_serving", 0)),
                float(rec.get("carbs_per_serving", 0)),
                float(rec.get("fat_per_serving", 0)),
                float(rec.get("fiber_per_serving", 0)),
                float(rec.get("sugar_per_serving", 0)),
                float(rec.get("sodium_mg_per_serving", 0)),
                float(rec.get("calories_per_100g", 0)),
                float(rec.get("protein_per_100g", 0)),
                float(rec.get("carbs_per_100g", 0)),
                float(rec.get("fat_per_100g", 0)),
                float(rec.get("fiber_per_100g", 0)),
                rec.get("ai_notes", ""),
                rec["name"],
            )
            db.execute(recipe_sql, r_params)
            inserted_recipes += getattr(db, "rowcount", 0) or 0

        db.commit()
        return {"inserted_foods": inserted_foods, "inserted_recipes": inserted_recipes}
    finally:
        if own_db:
            from db_pg import close_db
            close_db(db)


if __name__ == "__main__":
    res = seed_nourish_catalog()
    print(f"[seed_nourish] Seed complete: {res}")
